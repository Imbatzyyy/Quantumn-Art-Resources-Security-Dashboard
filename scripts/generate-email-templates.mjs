import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { authEmailTemplates } from '../netlify/functions/_shared/email-templates.mjs'

const check = globalThis.process.argv.includes('--check')
const directory = new globalThis.URL('../supabase/templates/', import.meta.url)
if (!check) await mkdir(directory, { recursive: true })
for (const template of authEmailTemplates) {
  const target = new globalThis.URL(`${template.id}.html`, directory)
  const content = `<!-- Generated by npm run emails:generate. Edit email-templates.mjs, not this file. -->\n${template.html}\n`
  if (check) {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Email template is out of date: ${template.id}`)
  } else await writeFile(target, content)
}
globalThis.console.log(`${check ? 'Verified' : 'Generated'} ${authEmailTemplates.length} branded Supabase email templates.`)
