  add constraint profiles_role_check
  check (role in ('employee', 'admin', 'hr_admin', 'payroll_admin', 'security_admin', 'auditor'));

create or replace function public.current_hrms_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select role
  from public.profiles
  where auth_user_id = (select auth.uid())
    and status = 'Active'
  limit 1
$$;

create or replace function public.has_hrms_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_hrms_role() = any(allowed_roles), false)
$$;

create or replace function public.is_hrms_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.has_hrms_role(array['admin', 'hr_admin', 'payroll_admin', 'security_admin'])
$$;

create or replace function public.is_active_hrms_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where auth_user_id = (select auth.uid())
      and status in ('Active', 'On Leave')
  )
$$;

