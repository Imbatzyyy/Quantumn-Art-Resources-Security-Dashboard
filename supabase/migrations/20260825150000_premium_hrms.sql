  internal_note boolean default false
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  employee text := public.current_employee_code();
  request_owner text;
  request_kind text;
  comment_id bigint;
  can_manage boolean := public.has_hrms_role(array['admin', 'hr_admin', 'payroll_admin']);
begin
  if employee is null or not public.is_active_hrms_user() then
    raise exception 'Active authentication is required';
  end if;
  if char_length(trim(comment_body)) not between 1 and 1000 then
    raise exception 'Use a comment between 1 and 1000 characters';
  end if;

  select employee_code, request_type into request_owner, request_kind
  from public.employee_requests
  where id = selected_request_id;

  if request_owner is null or (request_owner <> employee and not can_manage) then
    raise exception 'Request not found';
  end if;
  if public.current_hrms_role() = 'payroll_admin' and request_kind <> 'Payroll Concern' then
    raise exception 'Payroll administrators may respond only to payroll concerns';
  end if;
  if internal_note and not can_manage then
    raise exception 'Only an authorized administrator can add an internal note';
  end if;

  insert into public.request_comments
    (request_id, author_employee_code, body, is_internal)
  values
    (selected_request_id, employee, trim(comment_body), internal_note)
  returning id into comment_id;

  update public.employee_requests
  set status = case
        when request_owner = employee and status = 'More Information' then 'Submitted'
        else status
      end,
      updated_at = now()
  where id = selected_request_id;

  if can_manage and not internal_note and request_owner <> employee then
    perform public.notify_employee(
      request_owner,
      'Request',
      'New response on your request',
      'HR added a response to request #' || selected_request_id::text || '.',
      'requests',
      'View request'
    );
  end if;

  return comment_id;
end;
$$;

