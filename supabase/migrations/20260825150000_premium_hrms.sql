-- Replace the earlier broad policies so the new specialist roles stay scoped.
do $$
declare
  policy_record record;
begin
  for policy_record in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = any(array[
        'profiles', 'attendance', 'leave_requests', 'payroll', 'performance_reviews',
        'announcements', 'security_alerts', 'account_sessions', 'audit_logs',
        'employee_requests', 'request_comments', 'notifications',
        'employee_documents', 'document_acknowledgements', 'work_schedules',
        'employee_benefits', 'employee_goals', 'lifecycle_cases',
        'lifecycle_tasks', 'payroll_runs', 'performance_cycles'
      ])
  loop
    execute format(
      'drop policy if exists %I on %I.%I',
      policy_record.policyname,
      policy_record.schemaname,
      policy_record.tablename
    );
  end loop;
end $$;

