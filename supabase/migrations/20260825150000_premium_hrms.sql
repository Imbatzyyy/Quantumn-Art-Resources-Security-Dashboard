create or replace function public.notify_announcement_recipients()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.notifications
    (employee_code, category, title, message, destination, action_label)
  select employee_code, 'Announcement', new.title, new.content, 'home', 'Read update'
  from public.profiles
  where status in ('Active', 'On Leave') and role = 'employee';
  return new;
end;
$$;

drop trigger if exists notify_announcement_recipients on public.announcements;
create trigger notify_announcement_recipients
  after insert on public.announcements
  for each row execute procedure public.notify_announcement_recipients();

create or replace function public.notify_document_recipient()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.notifications
    (employee_code, category, title, message, destination, action_label)
  select profile.employee_code,
         'Document',
         case when new.requires_ack then 'Document requires acknowledgement' else 'New document available' end,
         new.title || ' is now available in your document vault.',
         'documents',
         'View document'
  from public.profiles profile
  where profile.status in ('Active', 'On Leave')
    and profile.role = 'employee'
    and (new.employee_code is null or profile.employee_code = new.employee_code);
  return new;
end;
$$;

