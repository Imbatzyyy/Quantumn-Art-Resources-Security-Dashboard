create or replace function public.review_employee_request(
  selected_request_id bigint,
  decision text,
  decision_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  request_owner text;
  request_subject text;
begin
  if not public.has_hrms_role(array['admin', 'hr_admin', 'payroll_admin']) then
    raise exception 'HR administrator access required';
  end if;
  if decision not in ('Under Review', 'More Information', 'Approved', 'Rejected', 'Completed') then
    raise exception 'Unsupported request decision';
  end if;
  if decision in ('More Information', 'Rejected')
     and char_length(trim(decision_reason)) < 3 then
    raise exception 'Explain what the employee needs to do or why the request was rejected';
  end if;
  if public.current_hrms_role() = 'payroll_admin'
     and not exists (
       select 1 from public.employee_requests
       where id = selected_request_id and request_type = 'Payroll Concern'
     ) then
    raise exception 'Payroll administrators may review only payroll concerns';
  end if;

  update public.employee_requests
  set status = decision,
      decision_note = nullif(trim(decision_reason), ''),
      assigned_to = coalesce(assigned_to, public.current_employee_code()),
      reviewed_by = public.current_employee_code(),
      reviewed_at = now(),
      updated_at = now()
  where id = selected_request_id
    and status not in ('Cancelled', 'Completed')
  returning employee_code, subject into request_owner, request_subject;

  if request_owner is null then
    raise exception 'Open request not found';
  end if;

  perform public.notify_employee(
    request_owner,
    'Request',
    'Request ' || lower(decision),
    request_subject || ' is now ' || decision || case
      when nullif(trim(decision_reason), '') is not null then ': ' || trim(decision_reason)
      else '.'
    end,
    'requests',
    'View request'
  );
end;
$$;

