-- Keep timestamps consistent across administrator and employee mutations.
create or replace function public.set_hrms_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  target_table text;
begin
  foreach target_table in array array[
    'employee_requests', 'employee_documents', 'work_schedules', 'employee_goals',
    'lifecycle_cases', 'lifecycle_tasks', 'payroll_runs', 'performance_cycles'
  ]
  loop
    execute format('drop trigger if exists set_updated_at on public.%I', target_table);
    execute format(
      'create trigger set_updated_at before update on public.%I for each row execute procedure public.set_hrms_updated_at()',
      target_table
    );
  end loop;
end $$;

