create trigger notify_document_recipient
  after insert on public.employee_documents
  for each row execute procedure public.notify_document_recipient();

create or replace function public.record_hrms_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_code text := public.current_employee_code();
  actor_name text;
  row_payload jsonb;
  target_label text;
begin
  if (select auth.uid()) is null then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  select concat(first_name, ' ', last_name)
  into actor_name
  from public.profiles
  where employee_code = actor_code;

  row_payload := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  target_label := coalesce(
    row_payload ->> 'employee_code',
    row_payload ->> 'alert_code',
    row_payload ->> 'session_code',
    row_payload ->> 'title',
    case when row_payload ? 'id' then replace(tg_table_name, '_', ' ') || ' ' || (row_payload ->> 'id') end,
    replace(tg_table_name, '_', ' ')
  );

  insert into public.audit_logs
    (actor_employee_code, actor_label, action, target, display_time)
  values
    (
      actor_code,
      coalesce(actor_name, 'Authenticated user'),
      initcap(lower(tg_op)) || ' ' || replace(tg_table_name, '_', ' '),
      target_label,
      to_char(timezone('Asia/Manila', now()), 'Mon DD, YYYY HH12:MI AM')
    );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

do $$
declare
  target_table text;
begin
  foreach target_table in array array[
    'profiles', 'attendance', 'leave_requests', 'payroll', 'performance_reviews',
    'announcements', 'security_alerts', 'account_sessions', 'employee_requests',
    'request_comments', 'employee_documents', 'document_acknowledgements',
    'work_schedules', 'employee_benefits', 'employee_goals', 'lifecycle_cases',
    'lifecycle_tasks', 'payroll_runs', 'performance_cycles'
  ]
  loop
    execute format('drop trigger if exists %I on public.%I', 'audit_' || target_table, target_table);
    execute format(
      'create trigger %I after insert or update or delete on public.%I for each row execute procedure public.record_hrms_audit()',
      'audit_' || target_table,
      target_table
    );
  end loop;
end $$;

