create sequence if not exists public.employee_number_seq start 1;

create table if not exists public.profiles (
  employee_code text primary key default ('EMP' || lpad(nextval('public.employee_number_seq')::text, 3, '0')),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  first_name text not null,
  last_name text not null,
  email text not null unique,
  role text not null default 'employee' check (role in ('employee', 'admin', 'security_admin')),
  department text not null,
  position text not null,
  status text not null default 'Active' check (status in ('Active', 'On Leave', 'Inactive')),
  salary numeric(12, 2) not null default 0 check (salary >= 0),
  phone text,
  hire_date date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists profiles_email_lower_idx on public.profiles (lower(email));
create index if not exists profiles_auth_user_id_idx on public.profiles (auth_user_id);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  employee_code text not null references public.profiles(employee_code),
  work_date date not null default current_date,
  clock_in time,
  clock_out time,
  status text not null default 'Present' check (status in ('Present', 'Late', 'Absent', 'On Leave')),
  hours numeric(5, 2) not null default 0 check (hours >= 0 and hours <= 24),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_code, work_date)
);

create index if not exists attendance_employee_date_idx
  on public.attendance (employee_code, work_date desc);

create table if not exists public.leave_requests (
  id bigint generated by default as identity primary key,
  employee_code text not null references public.profiles(employee_code),
  leave_type text not null check (leave_type in ('Vacation', 'Sick', 'Emergency', 'Other')),
  start_date date not null,
  end_date date not null,
  days integer not null check (days > 0),
  reason text not null check (char_length(reason) between 3 and 500),
  status text not null default 'Pending' check (status in ('Pending', 'Approved', 'Rejected')),
  reviewed_by text references public.profiles(employee_code),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create index if not exists leave_requests_employee_idx
  on public.leave_requests (employee_code, created_at desc);

create table if not exists public.payroll (
  id bigint generated by default as identity primary key,
  employee_code text not null references public.profiles(employee_code),
  period text not null,
  gross numeric(12, 2) not null check (gross >= 0),
  deductions numeric(12, 2) not null default 0 check (deductions >= 0),
  net numeric(12, 2) generated always as (gross - deductions) stored,
  status text not null default 'Draft' check (status in ('Draft', 'Processed', 'Paid')),
  payment_date date,
  created_at timestamptz not null default now(),
  unique (employee_code, period)
);

create table if not exists public.performance_reviews (
  id bigint generated by default as identity primary key,
  employee_code text not null references public.profiles(employee_code),
  reviewer_code text references public.profiles(employee_code),
  period text not null,
  score integer not null check (score between 0 and 100),
  goal_progress integer not null check (goal_progress between 0 and 100),
  rating text not null,
  comments text,
  created_at timestamptz not null default now(),
  unique (employee_code, period)
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 120),
  content text not null check (char_length(content) between 3 and 1000),
  priority text not null default 'Normal' check (priority in ('Normal', 'High')),
  author_employee_code text references public.profiles(employee_code),
  published_on date not null default current_date,
  created_at timestamptz not null default now()
