create or replace function public.current_employee_code()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select employee_code
  from public.profiles
  where auth_user_id = (select auth.uid())
  limit 1
$$;

create or replace function public.is_hrms_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where auth_user_id = (select auth.uid())
      and role in ('admin', 'security_admin')
      and status = 'Active'
  )
$$;

create or replace function public.link_auth_user_to_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles
  set auth_user_id = new.id,
      updated_at = now()
  where lower(email) = lower(new.email)
    and auth_user_id is null;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_link_profile on auth.users;
create trigger on_auth_user_created_link_profile
  after insert on auth.users
  for each row execute procedure public.link_auth_user_to_profile();

create or replace function public.update_own_profile(new_phone text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required';
  end if;

  update public.profiles
  set phone = nullif(trim(new_phone), ''),
      updated_at = now()
  where auth_user_id = (select auth.uid());

  if not found then
    raise exception 'HRMS profile not found';
  end if;
end;
$$;

create or replace function public.clock_attendance()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  employee text;
  existing public.attendance%rowtype;
  local_now timestamp := timezone('Asia/Manila', now());
begin
  employee := public.current_employee_code();
  if employee is null then
    raise exception 'HRMS profile not found';
  end if;

  select * into existing
  from public.attendance
  where employee_code = employee
    and work_date = local_now::date
  for update;

  if not found then
    insert into public.attendance (employee_code, work_date, clock_in, status, hours)
    values (employee, local_now::date, local_now::time, 'Present', 0);
  elsif existing.clock_out is null then
    update public.attendance
    set clock_out = local_now::time,
        hours = greatest(0, extract(epoch from (local_now::time - existing.clock_in)) / 3600),
        updated_at = now()
    where id = existing.id;
  else
    raise exception 'Attendance for today is already complete';
  end if;
end;
$$;

