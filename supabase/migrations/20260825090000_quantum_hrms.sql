create or replace function public.record_hrms_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_code text := public.current_employee_code();
  actor_name text;
  target_label text;
begin
  -- Do not turn migration/seed activity into user audit events.
  if (select auth.uid()) is null then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  select concat(first_name, ' ', last_name)
  into actor_name
  from public.profiles
  where employee_code = actor_code;

  target_label := case tg_table_name
    when 'profiles' then coalesce(new.employee_code, old.employee_code)
    when 'attendance' then coalesce(new.employee_code, old.employee_code)
    when 'leave_requests' then 'Leave request ' || coalesce(new.id, old.id)::text
    when 'announcements' then coalesce(new.title, old.title)
    when 'security_alerts' then coalesce(new.alert_code, old.alert_code)
    when 'account_sessions' then coalesce(new.session_code, old.session_code)
    else tg_table_name
  end;

  insert into public.audit_logs
    (actor_employee_code, actor_label, action, target, display_time)
  values
    (
      actor_code,
      coalesce(actor_name, 'Authenticated user'),
      initcap(lower(tg_op)) || ' ' || replace(tg_table_name, '_', ' '),
      target_label,
      to_char(timezone('Asia/Manila', now()), 'Mon DD, YYYY HH12:MI AM')
    );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

